/**
 * Icon names offered in admin pickers (services, steps, hero focus items).
 *
 * @return array<string,string> Icon name => human label.
 */
function riaz_icon_choices() {
	$choices = array();
	foreach ( array_keys( riaz_icon_library() ) as $name ) {
		if ( in_array( $name, array( 'menu', 'x', 'chevron-left', 'chevron-right', 'chevron-down', 'arrow-left', 'arrow-up', 'plus' ), true ) ) {
			continue;
		}
		$choices[ $name ] = ucwords( str_replace( '-', ' ', $name ) );
	}
	return $choices;
}

/**
 * Return inline SVG markup for an icon.
 *
 * @param string $name Icon name from the outline or brand library.
 * @param int    $size Pixel size.
 * @param array  $args Optional: 'class', 'stroke' (stroke width), 'label' (accessible name).
 * @return string
 */
function riaz_get_icon( $name, $size = 18, $args = array() ) {
	$args  = wp_parse_args(
		$args,
		array(
			'class'  => '',
			'stroke' => 2,
			'label'  => '',
		)
	);
	$size  = absint( $size );
	$brand = riaz_brand_icon_library();

	if ( isset( $brand[ $name ] ) ) {
		$paths = $brand[ $name ];
		$paint = 'fill="currentColor"';
	} else {
		$library = riaz_icon_library();
		if ( ! isset( $library[ $name ] ) ) {
			$name = 'sparkles';
		}
		$paths = $library[ $name ];
		$paint = sprintf( 'fill="none" stroke="currentColor" stroke-width="%s" stroke-linecap="round" stroke-linejoin="round"', esc_attr( (string) $args['stroke'] ) );
	}

	$a11y = $args['label']
		? sprintf( 'role="img" aria-label="%s"', esc_attr( $args['label'] ) )
		: 'aria-hidden="true" focusable="false"';

	$svg = sprintf(
		'<svg class="rp-icon rp-icon-%1$s %2$s" xmlns="http://www.w3.org/2000/svg" width="%3$d" height="%3$d" viewBox="0 0 24 24" %4$s %5$s>%6$s</svg>',
		esc_attr( $name ),
		esc_attr( $args['class'] ),
		$size,
		$paint,
		$a11y,
		$paths
	);

	/**
	 * Filter the icon markup, e.g. to swap in a different icon set.
	 *
	 * @param string $svg  SVG markup.
	 * @param string $name Icon name.
	 * @param int    $size Icon size.
	 */
	return apply_filters( 'riaz_icon', $svg, $name, $size );
}

/**
 * Echo an icon. The markup is built entirely from the trusted libraries above.
 *
 * @param string $name Icon name.
 * @param int    $size Pixel size.
 * @param array  $args See riaz_get_icon().
 */
function riaz_icon( $name, $size = 18, $args = array() ) {
	echo riaz_get_icon( $name, $size, $args ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- SVG built from internal whitelist.
}
